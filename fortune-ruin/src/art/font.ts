export type PixelFont = '5x7' | '3x5';

function glyph(font: PixelFont, ch: string): string[] | null {
  const table = font === '5x7' ? F57 : F35;
  const g = table[ch] ?? table[ch.toUpperCase()];
  return g ? g.split('|') : null;
}

export function fontHeight(font: PixelFont): number {
  return font === '5x7' ? 7 : 5;
}

export function measureText(text: string, font: PixelFont = '5x7', scale = 1, spacing = 1): number {
  let w = 0;
  for (const ch of text) {
    const g = glyph(font, ch);
    w += ((g ? g[0].length : 3) + spacing) * scale;
  }
  return Math.max(0, w - spacing * scale);
}

export function drawText(ctx: Ctx, text: string, x: number, y: number, color: string, font: PixelFont = '5x7', scale = 1, spacing = 1): number {
  ctx.fillStyle = color;
  let cx = Math.round(x);
  for (const ch of text) {
    const g = glyph(font, ch);
    if (!g) {
      cx += (3 + spacing) * scale;
      continue;
    }
    for (let row = 0; row < g.length; row++) {
      for (let col = 0; col < g[row].length; col++) {
        if (g[row][col] === '#') ctx.fillRect(cx + col * scale, Math.round(y) + row * scale, scale, scale);
      }
    }
    cx += (g[0].length + spacing) * scale;
  }
  return cx - x;
}

/** Text with a 1px drop shadow / outline for legibility on busy backgrounds. */
export function drawTextShadow(ctx: Ctx, text: string, x: number, y: number, color: string, shadow: string, font: PixelFont = '5x7', scale = 1): void {
  drawText(ctx, text, x + scale, y + scale, shadow, font, scale);
  drawText(ctx, text, x, y, color, font, scale);
}

export function drawTextCentered(ctx: Ctx, text: string, cx: number, y: number, color: string, font: PixelFont = '5x7', scale = 1, shadow?: string): void {
  const w = measureText(text, font, scale);
  const x = Math.round(cx - w / 2);
  if (shadow) drawTextShadow(ctx, text, x, y, color, shadow, font, scale);
  else drawText(ctx, text, x, y, color, font, scale);
}
